import { DOMWrapper, flushPromises, mount } from '@vue/test-utils';
import { describe, expect, it, vi } from 'vitest';
import { setElectronTestClient } from '../../test/client';
import SettingsBrowserPanel from '../SettingsBrowserPanel.vue';
import bitwardenIcon from '../../assets/browser-extensions/bitwarden.svg';
import onePasswordIcon from '../../assets/browser-extensions/1password.png';

describe('Browser extension settings', () => {
  it('manages shared extensions without an active agent and preserves failed updates', async () => {
    const id = 'nngceckbapebfimnlniiiahkandclblb';
    const manager = { id, name: 'Bitwarden', enabled: false, permissions: [] };
    const browserExtensions = vi.fn().mockResolvedValue({ extensions: [manager, { ...manager, id: 'aeblfdkhhhdcdjpifhhbdiojplfjncoa', name: '1Password' }] });
    setElectronTestClient({ browserExtensions });
    const wrapper = mount(SettingsBrowserPanel, { attachTo: document.body });
    await flushPromises();
    expect(wrapper.get('.settings-panel__banner').text()).toContain('Make the browser your own');
    expect(wrapper.get('article').find('img').attributes('alt')).toBe('');
    expect(wrapper.get('article').find('img').attributes('src')).toBe(bitwardenIcon);
    expect(wrapper.findAll('article')[1].get('img').attributes('src')).toBe(new URL(onePasswordIcon, location.href).href);
    let finishInstall!: (result: { extensions: typeof manager[]; message?: string }) => void;
    browserExtensions.mockImplementationOnce(() => new Promise((resolve) => { finishInstall = resolve; }));
    await wrapper.get('[aria-label="Install Bitwarden"]').trigger('click');
    const installButton = wrapper.get('[aria-label="Install Bitwarden"]');
    expect(installButton.attributes('aria-busy')).toBe('true');
    expect(installButton.text()).toContain('Installing');
    expect(installButton.attributes('disabled')).toBeDefined();
    expect(wrapper.get('[aria-label="Install 1Password"]').attributes('aria-busy')).toBeUndefined();
    expect(wrapper.text()).not.toContain('Working…');
    finishInstall({ extensions: [manager], message: 'Extension installed.' });
    await flushPromises();
    expect(wrapper.find('[role="status"]').exists()).toBe(false);
    expect(wrapper.get('[aria-label="Install Bitwarden"]').attributes('aria-busy')).toBeUndefined();
    expect(browserExtensions).toHaveBeenLastCalledWith(null, 'install', id);
    browserExtensions.mockResolvedValue({ extensions: [{ ...manager, enabled: true, version: '2026.10.0' }] });
    await wrapper.get('[aria-label="Install Bitwarden"]').trigger('click');
    await flushPromises();
    expect(wrapper.text()).toContain('2026.10.0');
    const menuItems = () => new DOMWrapper(document.body).findAll('[role="menuitem"]');
    const openActions = () => wrapper.get('[aria-label="Bitwarden actions"]').trigger('click');
    expect(wrapper.find('[aria-label="Update Bitwarden"]').exists()).toBe(false);
    expect(menuItems()).toHaveLength(0);
    await openActions();
    expect(menuItems().map((item) => item.text())).toEqual(['Update', 'Disable', 'Reinstall', 'Remove']);
    let failUpdate!: (error: Error) => void;
    browserExtensions.mockImplementationOnce(() => new Promise((_resolve, reject) => { failUpdate = reject; }));
    await menuItems()[0].trigger('click');
    expect(menuItems()).toHaveLength(0);
    expect(wrapper.get('[aria-label="Bitwarden actions"]').attributes('aria-busy')).toBe('true');
    expect(wrapper.get('[aria-label="Bitwarden actions"]').attributes('disabled')).toBeDefined();
    failUpdate(new Error('Download failed; installed version kept.'));
    await flushPromises();
    expect(wrapper.text()).toContain('Download failed; installed version kept.');
    expect(wrapper.get('[aria-label="Bitwarden actions"]').attributes('aria-busy')).toBeUndefined();
    expect(wrapper.text()).toContain('2026.10.0');
    browserExtensions.mockResolvedValue({ extensions: [{ ...manager, enabled: false, version: '2026.10.0' }] });
    await openActions();
    await menuItems()[1].trigger('click');
    await flushPromises();
    expect(browserExtensions).toHaveBeenLastCalledWith(null, 'disable', id);
    await openActions();
    expect(menuItems().map((item) => item.text())).toEqual(['Update', 'Enable', 'Reinstall', 'Remove']);
    await menuItems()[2].trigger('click');
    await flushPromises();
    expect(browserExtensions).toHaveBeenLastCalledWith(null, 'reinstall', id);
    browserExtensions.mockResolvedValue({ extensions: [manager], message: 'Extension removed.' });
    await openActions();
    await menuItems()[3].trigger('click');
    await flushPromises();
    expect(browserExtensions).toHaveBeenLastCalledWith(null, 'remove', id);
    expect(wrapper.find('[aria-label="Install Bitwarden"]').exists()).toBe(true);
    expect(wrapper.find('[role="status"]').exists()).toBe(false);
    wrapper.unmount();
  });
});
