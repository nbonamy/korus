export const appThemes: AppThemeDefinition[] = [...unsortedAppThemes].sort((left, right) => left.name.localeCompare(right.name));

export function themeById(themeId: string): AppThemeDefinition {
  return appThemes.find((themeDefinition) => themeDefinition.id === themeId)
    ?? appThemes.find((themeDefinition) => themeDefinition.id === appSystemPair.light)
    ?? appThemes[0];
}

export function themeIdForAppearance(themeId: string, appearance: AppThemeDefinition['appearance']): string {
  const selectedTheme = themeById(themeId);
  if (selectedTheme.appearance === appearance) {
    return selectedTheme.id;
  }

  const pair = themePairsById[selectedTheme.id];
  if (pair) {
    return pair[appearance];
  }

  return appThemes.find((themeDefinition) => themeDefinition.appearance === appearance)?.id ?? appSystemPair.light;
}

// System mode only follows the OS for the default light/dark pair, which is keyed on its light member.
export function themeIdForSystemMode(themeId: string): string {
  return themeId === appSystemPair.dark ? appSystemPair.light : themeId;
}

export function effectiveTheme(settings: AppThemeSettings, prefersDark: boolean): AppThemeDefinition {
  if (settings.mode === 'system' && settings.id === appSystemPair.light) {
    return themeById(prefersDark ? appSystemPair.dark : appSystemPair.light);
  }

  return themeById(settings.id);
}

function theme(seed: ThemeSeed): AppThemeDefinition {
  return {
    id: seed.id,
    name: seed.name,
    appearance: seed.appearance,
    colors: {
      '--color-primary': seed.primary,
      '--color-secondary': seed.secondary,
      '--color-surface': seed.surface,
      '--color-surface-lowest': seed.surfaceLowest,
      '--color-surface-low': seed.surfaceLow,
      '--color-surface-base': seed.surfaceBase,
      '--color-surface-high': seed.surfaceHigh,
      '--color-surface-highest': seed.surfaceHighest,
      '--color-on-surface': seed.text,
      '--color-on-surface-variant': seed.muted,
      '--color-outline': seed.outline,
      '--color-outline-variant': seed.outlineVariant,
    },
  };
}
