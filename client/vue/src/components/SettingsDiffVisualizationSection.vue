<template>
  <FormSection class="settings-diff-viz" :title="t('surface.diffViz.settingsTitle')" title-id="settings-workflows-diff-viz-title">
    <FormRow :title="t('surface.diffViz.style')" :description="t('surface.diffViz.styleDescription')">
      <template #control>
        <el-select :model-value="mode" :aria-label="t('surface.diffViz.style')" @update:model-value="updateMode">
          <el-option v-for="value in diffVisualizationModes" :key="value" :value="value" :label="t(`surface.diffViz.mode.${value}`)" />
        </el-select>
      </template>
    </FormRow>
    <FormRow :title="t('surface.diffViz.automatic')" :description="t('surface.diffViz.automaticDescription')">
      <template #control>
        <el-switch :model-value="automatic" :aria-label="t('surface.diffViz.automatic')" @update:model-value="updateAutomatic" />
      </template>
    </FormRow>
    <p v-if="error" role="alert">{{ error }}</p>
  </FormSection>
</template>
<script setup lang="ts">
import { ref, watch } from 'vue';
import { useI18n } from 'vue-i18n';
import type { AppGeneralSettings, UpdateSettingsInput, UpdateGeneralSettingsInput } from '@workspace/core/contracts';
import { diffVisualizationModes, type DiffVisualizationMode } from '@workspace/core/git-diff-viz';
import { useDebouncedSave } from '../shared/use-debounced-save';
import FormSection from '../shared/form/FormSection.vue';
import FormRow from '../shared/form/FormRow.vue';
const props = defineProps<{ settings: AppGeneralSettings; updateSettings?: (input: UpdateSettingsInput) => Promise<void> }>();
const { t } = useI18n();
const mode = ref<DiffVisualizationMode>(props.settings.diffVisualizationMode ?? 'polished');
const automatic = ref(props.settings.autoGenerateDiffViz === true);
let pending: UpdateGeneralSettingsInput = {};
const { schedule, error } = useDebouncedSave(async (general: UpdateGeneralSettingsInput) => {
  if (!props.updateSettings) throw new Error('Settings client unavailable.');
  await props.updateSettings({ general });
  for (const key of Object.keys(general) as Array<keyof UpdateGeneralSettingsInput>) if (pending[key] === general[key]) delete pending[key];
});
function updateMode(value: DiffVisualizationMode) { mode.value = value; pending = { ...pending, diffVisualizationMode: value }; schedule({ ...pending }); }
function updateAutomatic(value: boolean) { automatic.value = value; pending = { ...pending, autoGenerateDiffViz: value }; schedule({ ...pending }); }
watch(() => props.settings.diffVisualizationMode, value => { if (!('diffVisualizationMode' in pending)) mode.value = value ?? 'polished'; });
watch(() => props.settings.autoGenerateDiffViz, value => { if (!('autoGenerateDiffViz' in pending)) automatic.value = value === true; });
</script>
<style scoped>
.settings-diff-viz :deep(.el-select) { width: 220px; max-width: 100%; }
</style>
