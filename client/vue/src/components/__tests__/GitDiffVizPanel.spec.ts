import { flushPromises, mount } from '@vue/test-utils';
import { reactive } from 'vue';
import { describe, expect, it, vi } from 'vitest';
import { createEmptySnapshot } from '@workspace/core/snapshot';
import type { UpdateSettingsInput } from '@workspace/core/contracts';
import { stubElectronTestWindow } from '../../test/client';
import { diffVizSettingsKey } from '../diff-viz-settings';
import GitReviewPanel from '../GitReviewPanel.vue';
import type { SidePanelGitDiffState } from '../side-panel';

const diff = ['input', 'output', 'other'].map(name => `diff --git a/${name}.ts b/${name}.ts\n--- a/${name}.ts\n+++ b/${name}.ts\n@@ -1 +1 @@\n-old\n+new\n`).join('');
const diagram = { format: 'excalidraw', elements: [], groups: [], nodes: [{ id: 'result', label: 'Draft generation', status: 'changed', paths: ['input.ts', 'output.ts'], locations: [{ path: 'output.ts', line: 1, side: 'new' }] }] };
const canvas = { props: ['diagram'], emits: ['select'], template: '<button v-for="target in diagram.nodes" :key="target.id" @click="$emit(\'select\',target.paths,target.locations?.[0])">{{ target.label }}</button>' };
function setup(auto = false) {
  const snapshot = reactive(createEmptySnapshot());
  snapshot.general.autoGenerateDiffViz = auto;
  const generate = vi.fn().mockImplementation(async (_id, input) => { structuredClone(input); return { kind: 'viz', diagram }; });
  const cancel = vi.fn().mockResolvedValue(undefined);
  const updateSettings = vi.fn(async (input: UpdateSettingsInput) => { Object.assign(snapshot.general, input.general); return snapshot; });
  stubElectronTestWindow({ app: { generateAgentGitMessage: generate, cancelAgentGitMessage: cancel, updateSettings } });
  const wrapper = mount(GitReviewPanel, { props: { agent: { id: 'a', backend: 'claude', folder: '/repo' } as never,
    panel: { kind: 'gitDiff', title: 'Changes', diff, state: 'idle' } }, global: {
      provide: { [diffVizSettingsKey as symbol]: () => snapshot.general }, stubs: { GitDiffVizCanvas: canvas, GitDiffVizMermaid: canvas },
    } });
  const openViz = () => wrapper.get('.git-diff-view-toggle button:nth-child(2)').trigger('click');
  return { wrapper, generate, cancel, updateSettings, snapshot, openViz };
}

describe('Changes Viz workflow', () => {
  it('shuffles twenty loading labels per run, rotates every five seconds and releases the timer', async () => {
    // Protect against frozen loading copy, early rotation and timers surviving completion/unmount.
    vi.useFakeTimers({ toFake: ['setInterval', 'clearInterval'] });
    const random = vi.spyOn(Math, 'random').mockReturnValue(0.999);
    const { wrapper, generate, openViz } = setup();
    let resolve!: (value: unknown) => void;
    let reject!: (cause: Error) => void;
    generate.mockImplementation(() => new Promise((resolveRequest, rejectRequest) => { resolve = resolveRequest; reject = rejectRequest; }));
    try {
      await openViz(); await flushPromises();
      await wrapper.get('.diff-viz__generate').trigger('click'); await flushPromises();
      const button = () => wrapper.get('.diff-viz__generate');
      const first = button().text();
      expect(button().attributes('disabled')).toBeDefined();
      await vi.advanceTimersByTimeAsync(4_999);
      expect(button().text()).toBe(first);
      await vi.advanceTimersByTimeAsync(1);
      expect(button().text()).not.toBe(first);
      const labels = new Set([first, button().text()]);
      for (let index = 2; index < 20; index++) {
        await vi.advanceTimersByTimeAsync(5_000);
        labels.add(button().text());
      }
      expect(labels.size).toBe(20);
      await vi.advanceTimersByTimeAsync(5_000);
      expect(button().text()).toBe(first);
      reject(new Error('Try again')); await flushPromises();
      expect(button().text()).toBe('Generate');
      expect(vi.getTimerCount()).toBe(0);
      random.mockReturnValue(0);
      await button().trigger('click'); await flushPromises();
      const retryFirst = button().text();
      expect(retryFirst).not.toBe(first);
      await vi.advanceTimersByTimeAsync(5_000);
      expect(button().text()).not.toBe(retryFirst);
      resolve({ kind: 'viz', diagram }); await flushPromises();
      expect(button().text()).toBe('Regenerate');
      expect(vi.getTimerCount()).toBe(0);
      await button().trigger('click'); await flushPromises();
      const regeneratedFirst = button().text();
      await vi.advanceTimersByTimeAsync(5_000);
      expect(button().text()).not.toBe(regeneratedFirst);
      wrapper.unmount();
      expect(vi.getTimerCount()).toBe(0);
    } finally { if (wrapper.exists()) wrapper.unmount(); random.mockRestore(); vi.useRealTimers(); }
  });

  it('cancels the specific generation, discards late output and allows a fresh run', async () => {
    const { wrapper, generate, cancel, openViz } = setup();
    let resolve!: (value: unknown) => void;
    generate.mockReturnValueOnce(new Promise(done => { resolve = done; }));
    try {
      await openViz(); await flushPromises();
      await wrapper.get('.diff-viz__generate').trigger('click'); await flushPromises();
      expect(wrapper.find('.diff-viz__consent').exists()).toBe(false);
      const input = generate.mock.calls[0]![1];
      cancel.mockRejectedValueOnce(new Error('Could not stop generation'));
      await wrapper.get('.diff-viz__cancel').trigger('click'); await flushPromises();
      expect(wrapper.get('[role="alert"]').text()).toBe('Could not stop generation');
      expect(wrapper.get('.diff-viz__generate').attributes('disabled')).toBeDefined();
      expect(wrapper.get('.diff-viz__cancel').attributes('disabled')).toBeUndefined();
      await wrapper.get('.diff-viz__cancel').trigger('click'); await flushPromises();
      expect(cancel).toHaveBeenLastCalledWith('a', input.generationId);
      resolve({ kind: 'viz', diagram }); await flushPromises();
      expect(wrapper.text()).not.toContain('Draft generation');
      expect(wrapper.find('[role="alert"]').exists()).toBe(false);
      expect(wrapper.find('.diff-viz__cancel').exists()).toBe(false);
      expect(wrapper.get('.diff-viz__consent').text()).toBe('Do not ask again');
      expect(wrapper.get('.diff-viz__generate').attributes('disabled')).toBeUndefined();
      await wrapper.get('.diff-viz__generate').trigger('click'); await flushPromises();
      expect(generate.mock.calls[1]![1].generationId).not.toBe(input.generationId);
      expect(wrapper.text()).toContain('Draft generation');
    } finally { wrapper.unmount(); }
  });

  it('sends a cloneable request across IPC when the selected comparison comes from reactive app state', async () => {
    const { wrapper, generate, openViz } = setup();
    try {
      await wrapper.setProps({ panel: reactive<SidePanelGitDiffState>({ kind: 'gitDiff', title: 'Branch changes', diff, state: 'idle', target: { type: 'branch', baseRef: 'origin/main' }, sections: [{ scope: 'staged', diff }, { scope: 'unstaged', diff }] }) });
      await openViz(); await flushPromises();
      await wrapper.get('.diff-viz__generate').trigger('click'); await flushPromises();
      expect(generate).toHaveBeenCalledExactlyOnceWith('a', { kind: 'viz', generationId: expect.any(String), target: { type: 'branch', baseRef: 'origin/main' }, scopes: ['staged', 'unstaged'], mode: 'polished' });
      expect(() => structuredClone(generate.mock.calls[0]![1])).not.toThrow();
      expect(wrapper.find('[role="alert"]').exists()).toBe(false);
      expect(wrapper.text()).toContain('Draft generation');
    } finally { wrapper.unmount(); }
  });

  it('waits for an explicit Generate with auto off, caches the drawing and opens all files behind a semantic component', async () => {
    const { wrapper, generate, openViz } = setup();
    try {
      expect(wrapper.findAll('.git-diff-view-toggle button').map(item => item.text())).toStrictEqual(['Files', 'Viz', 'Map']);
      await openViz(); await flushPromises();
      expect(wrapper.text()).toContain('inspect this working folder');
      expect(wrapper.get('.diff-viz__consent').text()).toBe('Do not ask again');
      expect(wrapper.find('.diff-viz__legend').exists()).toBe(false);
      expect(generate).not.toHaveBeenCalled();
      await wrapper.setProps({ panel: { kind: 'gitDiff', title: 'Changes', diff, state: 'loading' } });
      expect(wrapper.get('.diff-viz__generate').attributes('disabled')).toBeDefined();
      await wrapper.setProps({ panel: { kind: 'gitDiff', title: 'Changes', diff, state: 'idle' } });
      await wrapper.get('.diff-viz__generate').trigger('click'); await flushPromises();
      expect(generate).toHaveBeenCalledExactlyOnceWith('a', { kind: 'viz', generationId: expect.any(String), target: { type: 'uncommitted' }, mode: 'polished' });
      expect(wrapper.find('.diff-viz__legend').exists()).toBe(true);
      await wrapper.findAll('button').find(button => button.text() === 'Draft generation')!.trigger('click'); await flushPromises();
      expect(wrapper.findAll('[data-code-path]').map(file => file.attributes('data-code-path'))).toStrictEqual(['input.ts', 'output.ts']);
      expect(wrapper.get('[data-code-path="output.ts"] [data-code-line="1"][data-code-side="new"]').attributes('data-viz-focus')).toBe('true');
      await openViz(); await flushPromises();
      expect(generate).toHaveBeenCalledOnce();
    } finally { wrapper.unmount(); }
  });

  it('saves Do not ask again to the Workflow preference only on Generate, and retries a failed save before calling the provider', async () => {
    const { wrapper, generate, updateSettings, snapshot, openViz } = setup();
    updateSettings.mockRejectedValueOnce(new Error('Settings unavailable'));
    try {
      await openViz(); await flushPromises();
      await wrapper.get('.diff-viz__consent input').setValue(true); await flushPromises();
      expect(updateSettings).not.toHaveBeenCalled();
      expect(generate).not.toHaveBeenCalled();
      await wrapper.get('.diff-viz__generate').trigger('click'); await flushPromises();
      expect(wrapper.get('[role="alert"]').text()).toContain('Settings unavailable');
      expect(generate).not.toHaveBeenCalled();
      await wrapper.get('.diff-viz__generate').trigger('click'); await flushPromises();
      expect(updateSettings).toHaveBeenLastCalledWith({ general: { autoGenerateDiffViz: true } });
      expect(snapshot.general.autoGenerateDiffViz).toBe(true);
      expect(generate).toHaveBeenCalledOnce();
      expect(wrapper.find('.diff-viz__consent').exists()).toBe(false);
      await wrapper.setProps({ panel: { kind: 'gitDiff', title: 'Changes', diff: diff + '\n', state: 'idle' } }); await flushPromises();
      expect(generate).toHaveBeenCalledTimes(2);
      expect(updateSettings).toHaveBeenCalledTimes(2);
    } finally { wrapper.unmount(); }
  });

  it('auto-generates after opting in through settings, ignores stale completions and recovers from provider errors', async () => {
    const { wrapper, generate, snapshot, openViz } = setup();
    let resolveFirst!: (value: unknown) => void;
    const first = new Promise(resolve => { resolveFirst = resolve; });
    generate.mockReturnValueOnce(first).mockRejectedValueOnce(new Error('Provider unavailable'));
    try {
      await openViz(); await flushPromises();
      expect(generate).not.toHaveBeenCalled();
      await wrapper.setProps({ visible: false });
      snapshot.general.autoGenerateDiffViz = true;
      await flushPromises(); expect(generate).not.toHaveBeenCalled();
      await wrapper.setProps({ visible: true });
      await flushPromises(); expect(generate).toHaveBeenCalledOnce();
      const replacement = diff.replaceAll('input.ts', 'request.ts');
      await wrapper.setProps({ panel: { kind: 'gitDiff', title: 'Changes', diff: replacement, state: 'idle' } }); await flushPromises();
      expect(generate).toHaveBeenCalledOnce();
      resolveFirst({ kind: 'viz', diagram }); await flushPromises();
      expect(generate).toHaveBeenCalledTimes(2);
      expect(wrapper.text()).toContain('Provider unavailable');
      expect(wrapper.findAll('button').some(button => button.text() === 'Draft generation')).toBe(false);
      await wrapper.get('.diff-viz__generate').trigger('click'); await flushPromises();
      expect(generate).toHaveBeenLastCalledWith('a', { kind: 'viz', generationId: expect.any(String), target: { type: 'uncommitted' }, mode: 'polished' });
      expect(wrapper.findAll('button').some(button => button.text() === 'Draft generation')).toBe(true);
    } finally { wrapper.unmount(); }
  });

  it('regenerates when the Git comparison changes even if its rendered patch is identical', async () => {
    const { wrapper, generate, openViz } = setup(true);
    try {
      await openViz(); await flushPromises();
      await wrapper.setProps({ panel: { kind: 'gitDiff', title: 'Changes', diff, state: 'idle', target: { type: 'commit', sha: 'abc123' } } }); await flushPromises();
      expect(generate).toHaveBeenCalledTimes(2);
      expect(generate).toHaveBeenLastCalledWith('a', { kind: 'viz', generationId: expect.any(String), target: { type: 'commit', sha: 'abc123' }, mode: 'polished' });
    } finally { wrapper.unmount(); }
  });

  it('switches to Fast from live settings and prevents a stale native scene from replacing it', async () => {
    const { wrapper, generate, snapshot, openViz } = setup(true);
    let resolveNative!: (value: unknown) => void;
    generate.mockReturnValueOnce(new Promise(resolve => { resolveNative = resolve; }));
    generate.mockResolvedValueOnce({ kind: 'viz', diagram: { format: 'mermaid', source: 'flowchart TB\nresult[Fast summary]', nodes: [{ ...diagram.nodes[0], label: 'Fast summary' }] } });
    try {
      await openViz(); await flushPromises();
      snapshot.general.diffVisualizationMode = 'fast'; await flushPromises();
      expect(generate).toHaveBeenCalledOnce();
      resolveNative({ kind: 'viz', diagram }); await flushPromises();
      expect(generate).toHaveBeenLastCalledWith('a', { kind: 'viz', generationId: expect.any(String), target: { type: 'uncommitted' }, mode: 'fast' });
      expect(wrapper.text()).toContain('Fast summary');
      expect(wrapper.text()).not.toContain('Draft generation');
    } finally { wrapper.unmount(); }
  });
});
