import { flushPromises, mount } from '@vue/test-utils';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { setElectronTestClient } from '../support/client';
import SettingsDictationPanel from '../../src/components/SettingsDictationPanel.vue';

const initial = { engine: 'apple' as const, openaiLiveTranscription: false, appleAvailable: true, hasApiKey: false, secureStorageAvailable: true };
describe('Dictation settings', () => {
  beforeEach(() => vi.useFakeTimers());
  afterEach(() => vi.useRealTimers());
  it('switches engines, autosaves a masked credential and removes it when cleared', async () => {
    const updateDictationSettings = vi.fn().mockImplementation(async input => ({ ...initial, engine: 'openai', hasApiKey: typeof input.apiKey === 'string', openaiLiveTranscription: input.openaiLiveTranscription ?? false }));
    setElectronTestClient({ getDictationSettings: async () => initial, updateDictationSettings });
    const wrapper = mount(SettingsDictationPanel);
    await flushPromises();
    expect(wrapper.get('h2').text()).toBe('Dictation');
    expect(wrapper.get('.settings-intro').text()).toContain('Turn speech into text');
    expect(wrapper.text()).not.toContain('Audio is sent');
    expect(wrapper.text()).not.toContain('No API key saved');
    expect(wrapper.text()).not.toContain('Remove key');
    expect(wrapper.find('[data-testid="save-dictation-key"]').exists()).toBe(false);
    await wrapper.findComponent({ name: 'ElSelect' }).vm.$emit('update:modelValue', 'openai');
    await flushPromises();
    expect(updateDictationSettings).toHaveBeenCalledWith({ engine: 'openai' });
    expect(wrapper.findAll('.form-row__copy strong').map(label => label.text())).toStrictEqual(['Engine', 'OpenAI API key', 'Live transcription']);
    const live = wrapper.findComponent({ name: 'ElSwitch' });
    expect(live.props('modelValue')).toBe(false);
    await live.vm.$emit('update:modelValue', true);
    await flushPromises();
    expect(updateDictationSettings).toHaveBeenLastCalledWith({ openaiLiveTranscription: true });
    await wrapper.get('input[type="password"]').setValue('test-secret');
    await vi.advanceTimersByTimeAsync(600);
    await flushPromises();
    expect(updateDictationSettings).toHaveBeenLastCalledWith({ apiKey: 'test-secret' });
    expect((wrapper.get('input[type="password"]').element as HTMLInputElement).value).toBe('••••••••');
    expect(wrapper.text()).not.toContain('API key saved');
    await wrapper.get('input[type="password"]').setValue('');
    await vi.advanceTimersByTimeAsync(600);
    await flushPromises();
    expect(updateDictationSettings).toHaveBeenLastCalledWith({ apiKey: null });
    expect((wrapper.get('input[type="password"]').element as HTMLInputElement).value).toBe('');
    await wrapper.get('input[type="password"]').setValue('last-key');
    wrapper.unmount();
    await flushPromises();
    expect(updateDictationSettings).toHaveBeenLastCalledWith({ apiKey: 'last-key' });
  });
  it('shows a saved credential as a mask after reopening and clears it without reading its value', async () => {
    const updateDictationSettings = vi.fn().mockImplementation(async input => ({ ...initial, engine: 'openai', hasApiKey: typeof input.apiKey === 'string', openaiLiveTranscription: input.openaiLiveTranscription ?? false }));
    setElectronTestClient({ getDictationSettings: async () => ({ ...initial, engine: 'openai', hasApiKey: true }), updateDictationSettings });
    const wrapper = mount(SettingsDictationPanel);
    await flushPromises();
    expect((wrapper.get('input[type="password"]').element as HTMLInputElement).value).toBe('••••••••');
    expect(updateDictationSettings).not.toHaveBeenCalled();
    await wrapper.get('input[type="password"]').setValue('••••••••replacement');
    await vi.advanceTimersByTimeAsync(600);
    expect(updateDictationSettings).toHaveBeenLastCalledWith({ apiKey: 'replacement' });
    await wrapper.get('input[type="password"]').setValue('');
    await vi.advanceTimersByTimeAsync(600);
    expect(updateDictationSettings).toHaveBeenLastCalledWith({ apiKey: null });
    wrapper.unmount();
  });
  it('keeps failed autosaves retryable without echoing provider errors or keys', async () => {
    setElectronTestClient({ getDictationSettings: async () => ({ ...initial, engine: 'openai', appleAvailable: false }), updateDictationSettings: async () => { throw new Error('sensitive provider detail'); } });
    const wrapper = mount(SettingsDictationPanel);
    await flushPromises();
    await wrapper.get('input[type="password"]').setValue('test-secret');
    await vi.advanceTimersByTimeAsync(600);
    await flushPromises();
    expect(wrapper.get('[role="alert"]').text()).toBe('Could not save dictation settings. Try again.');
    expect(wrapper.text()).not.toContain('sensitive provider detail');
    expect(wrapper.get('input[type="password"]').attributes('disabled')).toBeUndefined();
    wrapper.unmount();
  });
});
